    [Fact]
    public async Task FreshPostgres_AppliesLegacyAndSetupChain_AndUsesRuntimeMappings()
    {
        Assert.SkipUnless(_fixture.IsAvailable, "Docker with PostgreSQL 17 is required for this integration test.");
        await _fixture.ResetAsync();

        await using var context = CreateContext(_fixture.ConnectionString);
        await context.Database.MigrateAsync();
        Assert.Empty(await context.Database.GetPendingMigrationsAsync());

        context.Accounts.Add(new Account
        {
            Type = Account.AccountType.Admin,
            Username = "migration-baseline",
            PasswordHash = "hash",
            RandomSalt = "salt"
        });
        context.ConfigItems.Add(new ConfigItem
        {
            ConfigName = "migration-sentinel",
            ConfigValue = "preserved",
            IsEncrypted = false
        });
        context.SetupGrants.Add(new SetupGrant
        {
            Id = SetupGrant.SingletonId,
            GrantedTokenHash = "grant-hash",
            IssuedAtUtc = DateTime.UtcNow,
            ExpiresAtUtc = DateTime.UtcNow.AddHours(1),
            IsRevoked = false
        });
        context.SetupCompletionOperations.Add(new SetupCompletionOperation
        {
            Id = SetupCompletionOperation.SingletonId,
            OperationId = "operation-1",
            CreatedAtUtc = DateTime.UtcNow,
            RevocationPending = false
        });
        context.SetupRunLeases.Add(new SetupRunLease
        {
            Id = SetupRunLease.SingletonId,
            OwnerId = "owner-1",
            GrantHash = "grant-hash",
            Purpose = "setup",
            Generation = 1,
            LeaseUntilUtc = DateTime.UtcNow.AddMinutes(5)
        });
        var fence = await context.SetupMutationFences.SingleAsync();
        fence.Epoch = 1;
        await context.SaveChangesAsync();

        Assert.Equal("preserved", await context.ConfigItems.Where(x => x.ConfigName == "migration-sentinel").Select(x => x.ConfigValue).SingleAsync());
        Assert.Equal("migration-baseline", await context.Accounts.Select(x => x.Username).SingleAsync(x => x == "migration-baseline"));
        Assert.Equal("grant-hash", await context.SetupGrants.Select(x => x.GrantedTokenHash).SingleAsync());
        Assert.Equal(1, await context.SetupCompletionOperations.CountAsync());
        Assert.Equal(1, await context.SetupRunLeases.CountAsync());
        Assert.True(await TableExistsAsync(context, "DavItems"));
        Assert.True(await TableExistsAsync(context, "setup_grants"));
        var requiredTables = new[]
        {
            "Accounts", "DavItems", "DavNzbFiles", "DavRarFiles", "DavMultipartFiles", "QueueItems",
            "QueueNzbContents", "HistoryItems", "HealthCheckResults", "HealthCheckStats", "ConfigItems",
            "BlobCleanupItems", "MissingSegmentIds", "nntp_node_heartbeats", "nntp_connection_leases",
            "nntp_lease_epochs", "connection_pool_claims", "websocket_outbox", "auth_failures", "yenc_header_cache",
            "setup_grants", "setup_mutation_fence", "setup_completion_operations", "setup_run_leases"
        };
        var actualTables = await TableNamesAsync(context);
        Assert.True(requiredTables.All(actualTables.Contains), $"Missing tables: {string.Join(", ", requiredTables.Where(x => !actualTables.Contains(x)))}");
        Assert.Equal(ExpectedMigrations, await AppliedMigrationsAsync(context));
        Assert.Equal(ExpectedMigrations.Length, await MigrationHistoryCountAsync(context));
    }

    [Fact]
    public async Task FreshPostgres_WebsocketOutboxSeq_IsIdentityGeneratedAndIncreasing()
    {
        Assert.SkipUnless(_fixture.IsAvailable, "Docker with PostgreSQL 17 is required for this integration test.");
        await _fixture.ResetAsync();

        await using var context = CreateContext(_fixture.ConnectionString);
        await context.Database.MigrateAsync();

        context.WebsocketOutbox.Add(new WebsocketOutboxEntry
        {
            Topic = "migration-test-1",
            Payload = "payload-1"
        });
        await context.SaveChangesAsync();
        var first = await context.WebsocketOutbox
            .Where(x => x.Topic == "migration-test-1")
            .Select(x => x.Seq)
            .SingleAsync();

        context.WebsocketOutbox.Add(new WebsocketOutboxEntry
        {
            Topic = "migration-test-2",
            Payload = "payload-2"
        });
        await context.SaveChangesAsync();
        var second = await context.WebsocketOutbox
            .Where(x => x.Topic == "migration-test-2")
            .Select(x => x.Seq)
            .SingleAsync();

        Assert.NotEqual(0, first);
        Assert.True(second > first, $"Expected increasing identity sequence, got {first} then {second}.");
    }

    [Fact]
    public async Task ExistingBaselineHistory_SkipsLegacyAndAppliesOnlySetupMigrations()
    {
        Assert.SkipUnless(_fixture.IsAvailable, "Docker with PostgreSQL 17 is required for this integration test.");
        await _fixture.ResetAsync();

        await using var context = CreateContext(_fixture.ConnectionString);
