    [Fact]
    public async Task PostgresSetupMigrations_RollbackAndReupgrade_PreserveSentinel()
    {
        Assert.SkipUnless(_fixture.IsAvailable, "Docker with PostgreSQL 17 is required for this integration test.");
        await _fixture.ResetAsync();

        await using var context = CreateContext(_fixture.ConnectionString);
        await context.Database.MigrateAsync();
        context.ConfigItems.Add(new ConfigItem
        {
            ConfigName = "migration-roundtrip-sentinel",
            ConfigValue = "preserved",
            IsEncrypted = false
        });
        await context.SaveChangesAsync();

        await context.Database.MigrateAsync(Cutoff);
        Assert.False(await TableExistsAsync(context, "setup_run_leases"));
        Assert.Equal("preserved", await context.ConfigItems
            .Where(x => x.ConfigName == "migration-roundtrip-sentinel")
            .Select(x => x.ConfigValue)
            .SingleAsync());

        await context.Database.MigrateAsync();
        Assert.True(await TableExistsAsync(context, "setup_run_leases"));
        Assert.Equal("preserved", await context.ConfigItems
            .Where(x => x.ConfigName == "migration-roundtrip-sentinel")
            .Select(x => x.ConfigValue)
            .SingleAsync());
    }

