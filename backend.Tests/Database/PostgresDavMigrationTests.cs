    private static PostgresDavMigrationContext CreateUnconnectedContext()
        => CreateContext("Host=127.0.0.1;Port=1;Database=unconnected;Username=none;Password=none;Timeout=1");

    private static PostgresDavMigrationContext CreateContext(string connectionString)
    {
        var options = new DbContextOptionsBuilder<PostgresDavMigrationContext>()
            .UseNpgsql(connectionString)
            .Options;
        return new PostgresDavMigrationContext(options);
    }

    private static async Task<string[]> AppliedMigrationsAsync(PostgresDavMigrationContext context)
        => (await context.Database.GetAppliedMigrationsAsync()).ToArray();

    private static async Task<int> MigrationHistoryCountAsync(PostgresDavMigrationContext context)
    {
        await using var command = context.Database.GetDbConnection().CreateCommand();
        if (command.Connection!.State != ConnectionState.Open)
            await command.Connection.OpenAsync();
        command.CommandText = "SELECT COUNT(*) FROM \"__EFMigrationsHistory\";";
        return Convert.ToInt32(await command.ExecuteScalarAsync());
    }

    private static async Task<bool> TableExistsAsync(PostgresDavMigrationContext context, string tableName)
    {
        await using var command = context.Database.GetDbConnection().CreateCommand();
        if (command.Connection!.State != ConnectionState.Open)
            await command.Connection.OpenAsync();
        command.CommandText = """
            SELECT EXISTS (
                SELECT 1 FROM information_schema.tables
                WHERE table_schema = 'public' AND table_name = @tableName);
            """;
        var parameter = command.CreateParameter();
        parameter.ParameterName = "tableName";
        parameter.Value = tableName;
        command.Parameters.Add(parameter);
        return Convert.ToBoolean(await command.ExecuteScalarAsync());
    }

    private static async Task<HashSet<string>> TableNamesAsync(PostgresDavMigrationContext context)
    {
        await using var command = context.Database.GetDbConnection().CreateCommand();
        if (command.Connection!.State != ConnectionState.Open)
            await command.Connection.OpenAsync();
        command.CommandText = """
            SELECT table_name
            FROM information_schema.tables
            WHERE table_schema = 'public';
            """;
        var tables = new HashSet<string>(StringComparer.Ordinal);
        await using var reader = await command.ExecuteReaderAsync();
        while (await reader.ReadAsync())
            tables.Add(reader.GetString(0));
        return tables;
    }
